import { Connection, PublicKey } from "@solana/web3.js";
import { Resend } from "resend";
import axios from "axios";
import winston from "winston";
import * as dotenv from "dotenv";

dotenv.config();

const logger = winston.createLogger({
  level: "info",
  format: winston.format.combine(
    winston.format.timestamp(),
    winston.format.printf(({ timestamp, level, message }) => `[${timestamp}] [${level.toUpperCase()}]: ${message}`)
  ),
  transports: [new winston.transports.Console()],
});

const RESEND_API_KEY = process.env.RESEND_API_KEY || "re_dummy_test_key";
const SLACK_WEBHOOK_URL = process.env.SLACK_WEBHOOK_URL || "";
const SOLANA_RPC_WS = process.env.SOLANA_RPC_WS || "wss://api.devnet.solana.com";
const PROGRAM_ID = new PublicKey(process.env.PROGRAM_ID || "V1beM1croGrant11111111111111111111111111111");

const resend = new Resend(RESEND_API_KEY);

export class UniVibeEnterpriseRelay {
  private connection: Connection;

  constructor() {
    this.connection = new Connection("https://api.devnet.solana.com", {
      wsEndpoint: SOLANA_RPC_WS,
      commitment: "confirmed",
    });
  }

  public async startListening(): Promise<void> {
    logger.info(`Starting UniVibe Enterprise Event Mesh on Program: ${PROGRAM_ID.toBase58()}`);

    this.connection.onLogs(
      PROGRAM_ID,
      async (logs, ctx) => {
        if (logs.err) return;
        const signature = logs.signature;
        logger.info(`Detected program log in slot ${ctx.slot} | Signature: ${signature}`);

        for (const logLine of logs.logs) {
          if (logLine.includes("GrantDisbursedEvent")) {
            await this.handleDisbursementEvent(signature, logLine);
          } else if (logLine.includes("MilestoneSubmittedEvent")) {
            await this.handleMilestoneSubmitted(signature, logLine);
          }
        }
      },
      "confirmed"
    );
  }

  private async handleMilestoneSubmitted(signature: string, logLine: string): Promise<void> {
    logger.info(`[EVENT] Milestone Submission Detected: ${signature}`);
    
    if (SLACK_WEBHOOK_URL) {
      await axios.post(SLACK_WEBHOOK_URL, {
        text: `🚀 *UniVibe Milestone Submitted!*\n- *Signature:* \`${signature}\`\n- *Action:* Evaluator review required immediately on Devnet.\n- *Log:* \`${logLine}\``,
      }).catch(err => logger.error(`Slack webhook error: ${err.message}`));
    }
  }

  private async handleDisbursementEvent(signature: string, logLine: string): Promise<void> {
    logger.info(`[EVENT] Grant Disbursed Event Detected: ${signature}`);

    // Enterprise Slack Notification
    if (SLACK_WEBHOOK_URL) {
      await axios.post(SLACK_WEBHOOK_URL, {
        blocks: [
          {
            type: "section",
            text: {
              type: "mrkdwn",
              text: `💰 *KUBG Grant Milestone Disbursed!*\nProof confirmed and lamports released directly from PDA Vault.`,
            },
          },
          {
            type: "context",
            elements: [
              {
                type: "mrkdwn",
                text: `*Tx:* <https://explorer.solana.com/tx/${signature}?cluster=devnet|${signature.substring(0, 16)}...>`,
              },
            ],
          },
        ],
      }).catch(err => logger.error(`Slack notification failure: ${err.message}`));
    }

    // Enterprise Email Receipt via Resend
    const adminEmail = process.env.ADMIN_AUDIT_EMAIL || "grants@kubg-vibeathon.edu";
    try {
      await resend.emails.send({
        from: "UniVibe Oracle <onboarding@resend.dev>",
        to: adminEmail,
        subject: `[Audit Receipt] Milestone Escrow Release - Tx ${signature.substring(0, 8)}`,
        html: `
          <div style="font-family: Arial, sans-serif; padding: 20px; border: 1px solid #eaeaea; border-radius: 8px;">
            <h2 style="color: #6d28d9;">UniVibe Institutional Escrow Release</h2>
            <p>This is an automated cryptographic receipt generated by the UniVibe Event Engine.</p>
            <table style="width: 100%; border-collapse: collapse;">
              <tr><td style="padding: 8px 0;"><strong>Status:</strong></td><td style="color: green;">SUCCESS (Finalized)</td></tr>
              <tr><td style="padding: 8px 0;"><strong>Solana Signature:</strong></td><td><code>${signature}</code></td></tr>
              <tr><td style="padding: 8px 0;"><strong>Audit Network:</strong></td><td>Solana Devnet</td></tr>
            </table>
            <hr style="margin: 20px 0; border: 0; border-top: 1px solid #eee;" />
            <p style="font-size: 12px; color: #888;">Korea University Blockchain Group (KUBG) UNI Vibeathon MVP Infrastructure</p>
          </div>
        `,
      });
      logger.info(`Audit receipt dispatched via Resend to ${adminEmail}`);
    } catch (err: any) {
      logger.error(`Resend dispatch error: ${err.message}`);
    }
  }
}

if (require.main === module) {
  const relay = new UniVibeEnterpriseRelay();
  relay.startListening().catch((err) => {
    logger.error(`Relay failure: ${err.message}`);
    process.exit(1);
  });
}